import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { compile, optimize } from '@tailwindcss/node';
import { Scanner } from '@tailwindcss/oxide';
import { type Selector, transform } from 'lightningcss';

// Builds style.css: the preview's Tailwind classes, Tailwind's reset and select.css, every rule scoped to
// .discord-preview (the preview's root) and unlayered, so a page without Tailwind gets the preview as designed
// and nothing leaks out. `pnpm css` writes it; test/styles.test.ts fails when it's out of date.

export const OUT = fileURLToPath(new URL('../style.css', import.meta.url));
const ROOT = 'discord-preview';

const INPUT = `
@import "tailwindcss/theme.css";
@import "tailwindcss/preflight.css";
@import "tailwindcss/utilities.css";
@import "./src/select.css";
@source "./src/*.tsx";
@source not inline("container");
@source not inline("ring");
@source not inline("fixed");
@theme {
  --breakpoint-xs: 600px;
  --font-mono: "JetBrains Mono", ui-monospace, Menlo, monospace;
}
`;

// The preview's body text, and the colour of the selection ring (override --dp-ring and --dp-font on .discord-preview).
const ROOT_RULE = `.${ROOT} {
  font-size: 14px;
  line-height: 1.5;
  font-family: var(--dp-font, "gg sans", "Noto Sans", "Helvetica Neue", Helvetica, Arial, sans-serif);
  --dp-ring: #5865f2;
}
discord-preview {
  display: block;
}
`;

const root = { type: 'class', name: ROOT } as const;
const inside = { type: 'pseudo-class', kind: 'is', selectors: [[root], [root, { type: 'combinator', value: 'descendant' }, { type: 'universal' }]] } as const;

// `x` becomes `x:is(.discord-preview, .discord-preview *)`: the preview's root or anything in it.
function scoped(s: Selector): Selector {
  let at = s.length;
  for (let i = s.length - 1; i >= 0 && s[i]?.type !== 'combinator'; i--) if (s[i]?.type === 'pseudo-element') at = i;
  return [...s.slice(0, at), inside as never, ...s.slice(at)];
}

export async function buildCss() {
  const compiler = await compile(INPUT, { base: fileURLToPath(new URL('..', import.meta.url)), onDependency: () => {} });
  const scanner = new Scanner({ sources: compiler.sources });
  // The theme's variables go on the preview, not the page.
  const css = optimize(compiler.build(scanner.scan()), { minify: false }).code.replace(':root, :host {', `.${ROOT} {`);
  // shortcut: lightningcss 1.32 can't take back a returned rule that holds var(), so rules are only dropped or have their selectors rewritten
  const { code } = transform({
    filename: 'style.css',
    code: Buffer.from(css),
    visitor: {
      Rule: {
        'layer-block': (rule) => rule.value.rules,
        'layer-statement': () => [],
        style: (rule) => (rule.value.selectors.some((s) => s[0]?.type === 'type' && s[0].name === 'html') ? [] : undefined),
      },
      Selector: scoped,
    },
  });
  return `/* Generated by scripts/css.ts from src/: run \`pnpm css\` after changing the preview's classes. */\n${code.toString()}${ROOT_RULE}`;
}

if (import.meta.filename === process.argv[1]) writeFileSync(OUT, await buildCss());
